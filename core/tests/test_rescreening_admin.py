from core.tests.test_shared_fulltext import SharedFulltextFixture


def localized_models():
    return [model for model in apps.get_app_config('core').get_models()
            if model.__module__ in ('core.rescreening.models', 'core.fulltext.models')]


class RescreenAdminMetadataTests(SimpleTestCase):
    def test_migration_only_changes_presentation_metadata_not_database_definitions(self):
        from django.db.migrations.loader import MigrationLoader
        from django.db.migrations.writer import MigrationWriter
        from django.db.migrations.operations import AlterField, AlterModelOptions, SeparateDatabaseAndState
        loader = MigrationLoader(None)
        node = ('core', '0056_localize_rescreen_admin')
        before = loader.project_state([('core', '0055_rescreenexport_snapshot_size')])
        after = loader.project_state([node])
        container, = loader.disk_migrations[node].operations
        self.assertIsInstance(container, SeparateDatabaseAndState)
        self.assertEqual(container.database_operations, [])
        for operation in container.state_operations:
            self.assertIsInstance(operation, (AlterField, AlterModelOptions))
            if isinstance(operation, AlterField):
                key = ('core', operation.model_name)
                old = before.models[key].fields[operation.name].deconstruct()
                new = after.models[key].fields[operation.name].deconstruct()
                for definition in (old, new):
                    definition[3].pop('verbose_name', None)
                    definition[3].pop('choices', None)
                self.assertEqual(MigrationWriter.serialize(old), MigrationWriter.serialize(new), operation.name)

    def test_all_new_model_and_field_labels_are_chinese_or_standard_identifiers(self):
        identifiers = {'ID', 'DOI', 'PMID', 'PMCID', 'ISBN', 'ISSN'}
        for model in localized_models():
            with self.subTest(model=model.__name__):
                self.assertRegex(str(model._meta.verbose_name), r'[\u4e00-\u9fff]')
                self.assertEqual(model._meta.verbose_name_plural, model._meta.verbose_name)
                for field in model._meta.fields:
                    self.assertTrue(re.search(r'[\u4e00-\u9fff]', str(field.verbose_name))
                        or str(field.verbose_name) in identifiers, f'{model.__name__}.{field.name}: {field.verbose_name}')

    def test_admin_list_headers_including_fk_id_columns_are_localized(self):
        for model in localized_models():
            model_admin = admin.site._registry.get(model)
            if not model_admin:
                continue
            for name in model_admin.list_display:
                with self.subTest(model=model.__name__, column=name):
                    label = str(label_for_field(name, model, model_admin))
                    self.assertTrue(re.search(r'[\u4e00-\u9fff]', label) or label in {'ID', 'DOI', 'PMID', 'PMCID', 'ISBN', 'ISSN'}, label)

    def test_choice_codes_are_not_translated_in_storage(self):
        run = rs.RescreenRun(status='completed')
        self.assertEqual(run.get_status_display(), '已完成')
        self.assertEqual(run.status, 'completed')
        self.assertEqual(rs.RescreenReview(decision='included').get_decision_display(), '纳入')
        self.assertEqual(rs.RescreenExport(format='skip', mode='final').get_format_display(), '明确跳过导出')
        self.assertEqual(FulltextAsset(scan_status='not_configured').get_scan_status_display(), '未配置扫描服务')
        self.assertEqual(rs.RescreenSettings(pk=7).__str__(), '复筛设置 #7')
        self.assertEqual(apps.get_app_config('core').verbose_name, '平台管理')


class RescreenAdminPageTests(SharedFulltextFixture):
    def setUp(self):
        super().setUp()
        self.user.is_staff = self.user.is_superuser = True
        self.user.save(update_fields=['is_staff', 'is_superuser'])
        self.client.force_login(self.user)
        self.asset, refs = self.ready(references=True)
        self.ref = refs[0]
        self.corpus = RescreenCorpus.objects.get(project=self.project)
        criteria = RescreenCriteriaRevision.objects.create(corpus=self.corpus, revision=1, criteria=[])
        self.run = RescreenRun.objects.create(corpus=self.corpus, input_revision=1,
            criteria_revision=criteria, status='completed', config_snapshot={})

    def test_index_shows_chinese_names_not_autogenerated_english_plurals(self):
        response = self.client.get('/admin/')
        self.assertEqual(response.status_code, 200)
        text = response.content.decode()
        for label in ('平台管理', '复筛设置', 'AI 复筛运行', '候选全文', '全文查找任务', '复筛导出任务', '复筛审核历史'):
            self.assertIn(label, text)
        self.assertNotIn('Rescreen settingss', text)
        self.assertNotIn('Fulltext candidates', text)

    def test_every_registered_new_changelist_renders_without_private_file_url_errors(self):
        for model in localized_models():
            if model not in admin.site._registry:
                continue
            with self.subTest(model=model.__name__):
                response = self.client.get(f'/admin/core/{model._meta.model_name}/')
                self.assertEqual(response.status_code, 200)
                self.assertIn(str(model._meta.verbose_name), response.content.decode())

    def test_details_show_chinese_labels_and_state_and_keep_readonly_permissions(self):
        response = self.client.get(f'/admin/core/rescreenrun/{self.run.pk}/change/')
        self.assertEqual(response.status_code, 200)
        text = response.content.decode()
        for label in ('AI 复筛运行', '输入修订号', '排除标准修订', '已完成', '计费版本'):
            self.assertIn(label, text)
        response = self.client.get(f'/admin/core/fulltextasset/{self.asset.pk}/change/')
        self.assertEqual(response.status_code, 200)
        self.assertIn('文本提取状态', response.content.decode())
        request = RequestFactory().get('/admin/core/rescreenrun/')
        request.user = self.user
        model_admin = admin.site._registry[RescreenRun]
        self.assertFalse(model_admin.has_add_permission(request))
        self.assertFalse(model_admin.has_change_permission(request, self.run))
        self.assertFalse(model_admin.has_delete_permission(request, self.run))
        self.run.refresh_from_db()
        self.assertEqual(self.run.status, 'completed')
